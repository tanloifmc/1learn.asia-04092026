require('dotenv').config({ path: '.env.local' });
const { Pool } = require('pg');

const pool = new Pool({ connectionString: process.env.DIRECT_URL });

async function cleanFakeData() {
  try {
    console.log("Bắt đầu dọn dẹp dữ liệu fake (sessions không có responses)...\n");

    // 1. Tìm các session fake (completed nhưng có 0 responses)
    const findQuery = `
      SELECT s.id 
      FROM assessment_sessions s
      LEFT JOIN assessment_responses r ON s.id = r.session_id
      WHERE s.status = 'completed'
      GROUP BY s.id
      HAVING count(r.id) = 0
    `;
    const res = await pool.query(findQuery);
    const fakeSessionIds = res.rows.map(r => r.id);

    console.log(`Phát hiện ${fakeSessionIds.length} fake sessions.`);

    if (fakeSessionIds.length === 0) {
      console.log("Không có dữ liệu fake nào cần xóa.");
      return;
    }

    // 2. Xóa derived_profile_signals liên kết với user của các session này 
    // Wait, derived_profile_signals links to student_id. If the student ONLY has fake sessions, we delete their signals.
    // Let's delete signals tied to these specific assessment_results.
    // Wait, derived_profile_signals has 'assessment_result_id' or similar?
    // Let's check columns of derived_profile_signals.
    const sigCheck = await pool.query(`
      SELECT column_name FROM information_schema.columns 
      WHERE table_name = 'derived_profile_signals'
    `);
    const sigCols = sigCheck.rows.map(r => r.column_name);
    
    // Nếu derived_profile_signals có 'source_result_id' hoặc tương tự
    // Actually, it usually just has student_id. Let's delete signals for the students who own these fake sessions.
    // We only want to delete signals generated BY these sessions.
    
    console.log("Đang xóa dữ liệu...");

    // Bắt đầu transaction
    await pool.query('BEGIN');

    // Xóa trong bảng assessment_results (sẽ tự động cascade hoặc ta xóa thủ công)
    const delResults = await pool.query(`
      DELETE FROM assessment_results 
      WHERE session_id = ANY($1::uuid[])
      RETURNING id, student_id
    `, [fakeSessionIds]);
    console.log(`Đã xóa ${delResults.rowCount} dòng trong assessment_results.`);

    // Nếu bảng derived_profile_signals có cột source_result_id/assessment_result_id, xóa nó
    if (sigCols.includes('source_result_id')) {
      const delSignals = await pool.query(`
        DELETE FROM derived_profile_signals 
        WHERE source_result_id = ANY($1::uuid[])
      `, [delResults.rows.map(r => r.id)]);
      console.log(`Đã xóa ${delSignals.rowCount} dòng trong derived_profile_signals.`);
    } else {
      // Nếu chỉ có student_id, xóa toàn bộ signals của các học sinh đó
      // (Bởi vì học sinh test này chỉ có session fake)
      const studentIds = [...new Set(delResults.rows.map(r => r.student_id))];
      if (studentIds.length > 0) {
        const delSignals = await pool.query(`
          DELETE FROM derived_profile_signals 
          WHERE student_id = ANY($1::uuid[])
        `, [studentIds]);
        console.log(`Đã xóa ${delSignals.rowCount} fake signals trong derived_profile_signals.`);
      }
    }

    // Cuối cùng xóa sessions
    const delSessions = await pool.query(`
      DELETE FROM assessment_sessions
      WHERE id = ANY($1::uuid[])
    `, [fakeSessionIds]);
    console.log(`Đã xóa ${delSessions.rowCount} dòng trong assessment_sessions.`);

    await pool.query('COMMIT');
    console.log("\nHoàn tất! Dữ liệu giả đã được xóa sạch sẽ.");
    
  } catch (error) {
    await pool.query('ROLLBACK');
    console.error("LỖI:", error);
  } finally {
    pool.end();
  }
}

cleanFakeData();
